package org.synesis.cli;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.synesis.cli.bootstrap.CliRuntime;
import org.synesis.cli.terminal.ConsoleTerminal;
import org.synesis.cli.terminal.StatusRenderer;
import org.synesis.link.onboarding.Onboarding;
import picocli.CommandLine;

/**
 * Keeps the command list of {@code docs/cli/command-reference.md} equal to the CLI's own command tree, so a command
 * cannot be added, renamed or removed without the reference following. The prose around the list stays hand-written;
 * the list is generated from the commands' descriptions. To rewrite it after changing a command, run this test with
 * {@code SYNESIS_REGENERATE_COMMAND_REFERENCE=1}.
 */
final class CommandReferenceTest {

    private static final String BEGIN = "<!-- COMMAND-LIST-BEGIN generated by CommandReferenceTest from the command tree; change a command's description in its class, not here -->";
    private static final String END = "<!-- COMMAND-LIST-END -->";

    @TempDir
    Path tmp;

    @Test
    void theReferenceListsEveryCommandOfTheTree() throws IOException {
        String reference = generatedBlock(Files.readString(referenceFile(), StandardCharsets.UTF_8));
        for (String name : commands(tree())) {
            assertTrue(reference.lines().anyMatch(line -> line.equals(name) || line.startsWith(name + "  ")), "docs/cli/command-reference.md does not list: " + name);
        }
    }

    @Test
    void theReferenceExplainsEveryErrorCodeTheCommandsPrint() throws IOException {
        String document = Files.readString(referenceFile(), StandardCharsets.UTF_8);
        for (String code : org.synesis.cli.command.ErrorShape.codes()) {
            assertTrue(document.contains("`" + code + "`"), "docs/cli/command-reference.md does not explain the error code " + code);
        }
        for (int exit : List.of(0, 1, 2, 3, 10, 11, 12, 13, 14, 15, 70)) {
            assertTrue(document.contains("| `" + exit + "` |"), "docs/cli/command-reference.md does not list exit code " + exit);
        }
    }

    @Test
    void theListIsTheOneTheTreeGenerates() throws IOException {
        Path file = referenceFile();
        String document = Files.readString(file, StandardCharsets.UTF_8);
        String expected = BEGIN + "\n" + generate(tree()) + END;
        if (System.getenv("SYNESIS_REGENERATE_COMMAND_REFERENCE") != null) {
            String eol = document.contains("\r\n") ? "\r\n" : "\n";
            int start = document.indexOf(BEGIN);
            int end = document.indexOf(END) + END.length();
            Files.writeString(file, document.substring(0, start) + expected.replace("\n", eol) + document.substring(end), StandardCharsets.UTF_8);
            return;
        }
        assertEquals(expected, generatedBlock(document), () -> "docs/cli/command-reference.md is out of date; replace the block between the COMMAND-LIST markers with:\n" + expected);
    }

    private CommandLine tree() {
        ConsoleTerminal terminal = new ConsoleTerminal(new PrintStream(new ByteArrayOutputStream(), true, StandardCharsets.UTF_8), new PrintStream(new ByteArrayOutputStream(), true, StandardCharsets.UTF_8));
        return SynesisCli.commandTree(new CliRuntime(new Onboarding(tmp.resolve("profile"), new StatusRenderer(terminal)), terminal));
    }

    /**
     * The block of the document between the markers, markers included, with line ends as {@code \n}.
     */
    private static String generatedBlock(String document) {
        String text = document.replace("\r\n", "\n");
        int start = text.indexOf(BEGIN);
        int end = text.indexOf(END);
        assertTrue(start >= 0 && end > start, "docs/cli/command-reference.md has no COMMAND-LIST markers");
        return text.substring(start, end + END.length());
    }

    private static Path referenceFile() {
        Path directory = Path.of("").toAbsolutePath();
        while (directory != null && !Files.isRegularFile(directory.resolve("docs/cli/command-reference.md"))) {
            directory = directory.getParent();
        }
        assertTrue(directory != null, "docs/cli/command-reference.md not found above " + Path.of("").toAbsolutePath());
        return directory.resolve("docs/cli/command-reference.md");
    }

    /**
     * Every visible command, parents before their subcommands, in registration order.
     */
    private static List<CommandLine> visible(CommandLine command) {
        List<CommandLine> commands = new ArrayList<>();
        command.getSubcommands().values().stream().distinct().filter(sub -> !sub.getCommandSpec().usageMessage().hidden()).forEach(sub -> {
            commands.add(sub);
            commands.addAll(visible(sub));
        });
        return commands;
    }

    private static List<String> commands(CommandLine root) {
        return visible(root).stream().map(command -> name(command)).toList();
    }

    /**
     * The command as typed after {@code synesis}.
     */
    private static String name(CommandLine command) {
        return command.getCommandSpec().qualifiedName(" ").substring("synesis ".length());
    }

    /**
     * One line per command: its name and the first sentence of its description, names padded to one column.
     */
    private static String generate(CommandLine root) {
        List<CommandLine> commands = visible(root);
        int width = commands.stream().mapToInt(command -> name(command).length()).max().orElse(0);
        StringBuilder block = new StringBuilder("```text\n");
        for (CommandLine command : commands) {
            String[] lines = command.getCommandSpec().usageMessage().description();
            String text = lines.length == 0 ? "" : lines[0].split("%n", 2)[0].strip();
            int sentence = text.indexOf(". ");
            String description = sentence < 0 ? text : text.substring(0, sentence + 1);
            block.append(String.format("%-" + width + "s  %s", name(command), description).stripTrailing()).append('\n');
        }
        return block.append("```\n").toString();
    }
}
